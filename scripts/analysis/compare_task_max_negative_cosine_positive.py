#!/usr/bin/env python3
"""Compare negative-score + cosine>0 rates across task-max scatter datasets.

This script is designed for outputs generated by:
  scripts/analysis/Bash_Scripts/run_pairdiff_task_max_scatter.sh

It compares two datasets (default: icse26 and icse26_val_1_4) for
CodeLlama-7b-Instruct-hf and reports:
  percentage of points with:
    - negative score outcome (correct is not highest in task), and
    - cosine_similarity > 0

To avoid double-counting multiple code options per task, rows are grouped by
(fold, layer, task_id) and each group is counted once. A group is considered
"matched" if ANY row in that group satisfies both conditions.
"""

from __future__ import annotations

import argparse
import csv
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Sequence, Tuple


DEFAULT_MODEL_SAFE = "codellama__CodeLlama-7b-Instruct-hf"
DEFAULT_BENCHMARK = "bigcodebench"
DEFAULT_SPLIT = "test"
DEFAULT_FOLDS = list(range(10))


@dataclass
class DatasetSummary:
    name: str
    layers: List[int]
    raw_rows: int
    dedup_points: int
    matched_points: int

    @property
    def percentage(self) -> float:
        if self.dedup_points == 0:
            return 0.0
        return 100.0 * self.matched_points / self.dedup_points


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Compare percentage of deduplicated task-max scatter points with "
            "negative score and cosine_similarity > 0."
        )
    )
    parser.add_argument("--model-safe", default=DEFAULT_MODEL_SAFE)
    parser.add_argument("--benchmark", default=DEFAULT_BENCHMARK)
    parser.add_argument("--split", default=DEFAULT_SPLIT)
    parser.add_argument("--folds", nargs="+", type=int, default=DEFAULT_FOLDS)
    parser.add_argument("--layers", default="scatter-cross-fold", help="scatter-cross-fold or comma-separated list")

    parser.add_argument(
        "--icse26-task-max-root",
        type=Path,
        default=Path(
            "outputs/phase2_task2_task_max/top_percentile/"
            "codellama__CodeLlama-7b-Instruct-hf/icse26/bigcodebench/id/test"
        ),
    )
    parser.add_argument(
        "--icse26-results-root",
        type=Path,
        default=Path("results"),
    )
    parser.add_argument(
        "--icse26-scatter-root",
        type=Path,
        default=Path(
            "outputs/phase2_task2_task_max/scatter_cross_fold/"
            "codellama__CodeLlama-7b-Instruct-hf/icse26/bigcodebench/id/test"
        ),
    )
    parser.add_argument(
        "--icse26-val-task-max-root",
        type=Path,
        default=Path(
            "outputs/phase2_task2_task_max/icse26_val_1_4/"
            "codellama__CodeLlama-7b-Instruct-hf/icse26_val_1_4/bigcodebench/id/test"
        ),
    )
    parser.add_argument(
        "--icse26-val-results-root",
        type=Path,
        default=Path("results_icse26_val_1_4"),
    )
    parser.add_argument(
        "--icse26-val-scatter-root",
        type=Path,
        default=Path(
            "outputs/phase2_task2_task_max/scatter_cross_fold/icse26_val_1_4/"
            "codellama__CodeLlama-7b-Instruct-hf/icse26_val_1_4/bigcodebench/id/test"
        ),
    )
    return parser.parse_args()


def _is_negative_and_positive_cosine(row: Dict[str, str]) -> bool:
    # Negative score side in task-max scatter: incorrect beats correct.
    negative = int(float(row["correct_highest_in_task"])) == 0
    return negative and float(row["cosine_similarity"]) > 0.0


def _find_fold_csv(task_max_root: Path, fold: int) -> Path:
    matches = sorted(task_max_root.glob(f"fold_{fold}/**/pairdiff_task_max_cosine.csv"))
    if not matches:
        raise FileNotFoundError(f"No pairdiff_task_max_cosine.csv found under {task_max_root}/fold_{fold}")
    return matches[0]


def _load_rows(csv_path: Path) -> List[Dict[str, str]]:
    with open(csv_path, newline="") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise ValueError(f"CSV is empty: {csv_path}")
    return rows


def _layers_from_scatter_pngs(scatter_root: Path) -> List[int]:
    layers: List[int] = []
    pattern = re.compile(r"layer_(\d+)_cosine_task_max_scatter_cross_fold\.png$")
    for p in sorted(scatter_root.glob("layer_*_cosine_task_max_scatter_cross_fold.png")):
        m = pattern.search(p.name)
        if m:
            layers.append(int(m.group(1)))
    if not layers:
        raise FileNotFoundError(f"No scatter_cross_fold layer PNGs found in: {scatter_root}")
    return sorted(set(layers))


def _parse_layers_arg(layers_arg: str, scatter_root: Path) -> List[int]:
    if layers_arg == "scatter-cross-fold":
        return _layers_from_scatter_pngs(scatter_root)
    values = [v.strip() for v in layers_arg.split(",") if v.strip()]
    if not values:
        raise ValueError("Invalid --layers value")
    return sorted({int(v) for v in values})


def _summarize_dataset(
    name: str,
    task_max_root: Path,
    scatter_root: Path,
    folds: Sequence[int],
    layers_arg: str,
) -> DatasetSummary:
    layers = _parse_layers_arg(layers_arg, scatter_root)
    layer_set = set(layers)
    grouped: Dict[Tuple[int, int, str], List[Dict[str, str]]] = {}
    raw_rows = 0

    for fold in folds:
        rows = _load_rows(_find_fold_csv(task_max_root, fold))
        for row in rows:
            layer = int(row["layer"])
            if layer not in layer_set:
                continue
            raw_rows += 1
            grouped.setdefault((fold, layer, row["task_id"]), []).append(row)

    matched_points = sum(
        1 for dup_rows in grouped.values() if any(_is_negative_and_positive_cosine(r) for r in dup_rows)
    )

    return DatasetSummary(
        name=name,
        layers=layers,
        raw_rows=raw_rows,
        dedup_points=len(grouped),
        matched_points=matched_points,
    )


def _format_summary(summary: DatasetSummary) -> str:
    return (
        f"{summary.name:14} "
        f"pct={summary.percentage:7.3f}% "
        f"(matched={summary.matched_points}, dedup_points={summary.dedup_points}, "
        f"raw_rows={summary.raw_rows}, layers={len(summary.layers)})"
    )


def main() -> None:
    args = parse_args()

    icse26 = _summarize_dataset(
        name="icse26",
        task_max_root=args.icse26_task_max_root.resolve(),
        scatter_root=args.icse26_scatter_root.resolve(),
        folds=args.folds,
        layers_arg=args.layers,
    )
    icse26_val = _summarize_dataset(
        name="icse26_val_1_4",
        task_max_root=args.icse26_val_task_max_root.resolve(),
        scatter_root=args.icse26_val_scatter_root.resolve(),
        folds=args.folds,
        layers_arg=args.layers,
    )

    print("Negative-score + cosine>0 comparison (deduplicated by fold/layer/task_id)")
    print(_format_summary(icse26))
    print(_format_summary(icse26_val))
    print(f"delta(icse26 - icse26_val_1_4) = {icse26.percentage - icse26_val.percentage:+.3f} pct points")


if __name__ == "__main__":
    main()
